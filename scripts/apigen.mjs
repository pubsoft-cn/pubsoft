#!/usr/bin/env node
/**
 * PubSoft API client codegen — pulls a PubSoft.AspNetCore.Docs catalog and emits a
 * clean, typed TypeScript client (no Swagger/OpenAPI needed).
 *
 *   node apigen.mjs http://host:5090/docs/catalog -o api-client.ts [--base /api] [--fetch-client]
 *
 * Type inference is example-driven: overlay `example` payloads define response
 * interfaces precisely (far cleaner than OpenAPI schema guessing). Endpoints without
 * an example emit `Promise<unknown>`.
 */
import { writeFileSync } from 'node:fs';
import { basename } from 'node:path';

const [,, ...argv] = process.argv;
const url = argv.find(a => /^https?:/.test(a));
const outIdx = argv.indexOf('-o');
const out = outIdx > -1 ? argv[outIdx + 1] : 'api-client.ts';
const stripPrefix = (() => { const i = argv.indexOf('--base'); return i > -1 ? argv[i + 1] : '/api'; })();

if (!url) { console.error('usage: node apigen.mjs <catalog-url> -o api-client.ts [--base /api]'); process.exit(1); }

const catalog = await (await fetch(url)).json();

// ---- naming ------------------------------------------------------------------
const seen = new Map();
function fnName(method, path) {
    // /api/v2/report/overview -> reportOverview ; /message/{src}/onlineorder -> postMessageOnlineorder
    const segs = path.split('/').filter(s => s && s !== 'api' && !/^v\d+$/.test(s));
    const parts = segs.map(s => s.replace(/[{}]/g, '').replace(/[^a-zA-Z0-9]+(.)/g, (_, c) => c.toUpperCase()));
    let name = method.toLowerCase()
        + parts.map(p => p[0]?.toUpperCase() + p.slice(1)).join('');
    name = name.replace(/[^a-zA-Z0-9]/g, '');
    if (seen.has(name)) { const n = seen.get(name) + 1; seen.set(name, n); name += n; } else seen.set(name, 1);
    return name;
}
function ifaceName(method, path) {
    const segs = path.split('/').filter(s => s && s !== 'api' && !/^v\d+$/.test(s));
    return segs.map(s => s.replace(/[{}]/g, '')).map(p => p[0]?.toUpperCase() + p.slice(1)).join('') + 'Response';
}

// ---- example-driven type inference --------------------------------------------
const ifaces = new Map(); // name -> ts source
function tsType(v, hint) {
    if (v === null || v === undefined) return 'unknown';
    if (Array.isArray(v)) return v.length ? `${tsType(v[0], hint)}[]` : 'unknown[]';
    switch (typeof v) {
        case 'number': return 'number';
        case 'string': return 'string';
        case 'boolean': return 'boolean';
        case 'object': {
            const name = hint;
            if (!ifaces.has(name)) {
                const fields = Object.entries(v).map(([k, val]) =>
                    `  ${/^[$_a-zA-Z][\w$]*$/.test(k) ? k : JSON.stringify(k)}${val === null ? '?' : ''}: ${tsType(val, name + '_' + k)};`);
                ifaces.set(name, `export interface ${name} {\n${fields.join('\n')}\n}`);
            }
            return name;
        }
    }
    return 'unknown';
}

// ---- CLR type → TS -------------------------------------------------------------
const clr2ts = t => ({
    String: 'string', Int32: 'number', Int64: 'number', Decimal: 'number', Double: 'number',
    Single: 'number', Boolean: 'boolean', DateTime: 'string', DateTimeOffset: 'string',
    'DateTime?': 'string', 'Int32?': 'number', 'Int64?': 'number', 'Decimal?': 'number',
    'Boolean?': 'boolean'
}[t] ?? (t.startsWith('List<') ? 'string[]' : t.endsWith('[]') ? 'string[]' : 'any'));

// ---- emit ----------------------------------------------------------------------
const lines = [
    `// generated by pubsoft apigen from ${url} — do not edit`,
    `// catalog: ${catalog.title || ''} @ ${catalog.generatedAt}`,
    ``,
    `const BASE = (import.meta as any).env?.VITE_API_BASE ?? '';`,
    `let token = '';`,
    `export const setToken = (t: string) => { token = t; };`,
    ``,
    `async function req<T>(method: string, path: string, query?: Record<string, any>, body?: any): Promise<T> {`,
    `  const u = new URL(BASE + path, location.origin);`,
    `  for (const [k, v] of Object.entries(query ?? {})) if (v !== undefined && v !== null) u.searchParams.set(k, String(v));`,
    `  const res = await fetch(u.toString(), {`,
    `    method,`,
    `    headers: { ...(body ? { 'Content-Type': 'application/json' } : {}), ...(token ? { Authorization: 'Bearer ' + token } : {}) },`,
    `    body: body ? JSON.stringify(body) : undefined,`,
    `  });`,
    `  if (!res.ok) throw new Error(\`\${method} \${path}: \${res.status}\`);`,
    `  if (res.status === 204 || res.headers.get('content-length') === '0') return undefined as T;`,
    `  return res.json();`,
    `}`,
    ``,
    `export const api = {`
];

const endpointFns = [];
for (const g of catalog.groups) {
    for (const e of g.endpoints) {
        if (e.method === 'WS' || e.method === 'CONNECT') continue;
        const name = fnName(e.method, e.path);
        const retName = ifaceName(e.method, e.path);
        const ret = e.example ? tsType(e.example, retName) : 'unknown';

        const pathParams = (e.path.match(/\{(\w+)\}/g) || []).map(s => s.slice(1, -1));
        const queryParams = (e.parameters || []).filter(p =>
            p.at && p.at.toLowerCase() !== 'path' && p.at.toLowerCase() !== 'body' && p.name && !pathParams.includes(p.name));
        const bodyParam = (e.parameters || []).find(p => p.at && p.at.toLowerCase() === 'body');

        const args = [];
        for (const pp of pathParams) args.push(`${pp}: string`);
        if (queryParams.length)
            args.push(`query?: { ${queryParams.map(p => `${p.name}${p.required ? '' : '?'}: ${clr2ts(p.type)}`).join('; ')} }`);
        if (bodyParam) args.push(`body: any /* ${bodyParam.type} */`);

        // 安全：path 进模板字符串前转义 ` 和 $ —— 防 catalog 内容注入生成代码；{param} 再还原成插值
        const safePath = String(e.path).replace(/[`$]/g, c => '\\' + c);
        const pathExpr = '`' + safePath.replace(/\{(\w+)\}/g, (_, k) => `\${${k}}`) + '`';
        const queryExpr = queryParams.length ? 'query' : 'undefined';
        const bodyExpr = bodyParam ? 'body' : 'undefined';
        const doc = [e.summary, e.note].filter(Boolean).join(' — ');

        endpointFns.push(
            `${doc ? `  /** ${doc.replace(/\*\//g, '* /')} */\n` : ''}` +
            `  ${name}: (${args.join(', ')}) => req<${ret}>('${e.method}', ${pathExpr}, ${queryExpr}, ${bodyExpr}),`
        );
    }
}
lines.push(...endpointFns, `};`, ``);

// interfaces appended after api object so generation order is stable
const ifaceSrc = [...ifaces.values()].join('\n\n');
writeFileSync(out, lines.join('\n') + ifaceSrc + '\n');
console.log(`wrote ${out}: ${endpointFns.length} endpoints, ${ifaces.size} interfaces`);
