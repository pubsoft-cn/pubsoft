using System.Reflection;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Serialization;
using System.Xml.Linq;
using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Routing;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Options;

namespace PubSoft.Edge;

/// <summary>
/// Edge OpenAPI options — the gateway is a single method-dispatch endpoint, so
/// Swashbuckle-style scanners cannot see handlers. This doc is generated by reflecting
/// the registered <see cref="IEdgeHandler"/> set instead.
///
/// The document endpoint exposes the full method catalog and parameter schemas —
/// mapped only in Development unless <see cref="DevelopmentOnly"/> is explicitly
/// disabled (then gate by network or auth policy yourself).
/// </summary>
public sealed class EdgeOpenApiOptions
{
    public const string SectionName = "Edge:OpenApi";
    private readonly TimeProvider _timeProvider = TimeProvider.System;

    /// <summary>Path of the OpenAPI JSON document.</summary>
    public string DocumentPath { get; set; } = "/openapi.json";

    /// <summary>Path of the Swagger UI page.</summary>
    public string UiPath { get; set; } = "/docs";

    /// <summary>Whether to serve the Swagger UI page (loads assets from <see cref="SwaggerUiCssUrl"/>/<see cref="SwaggerUiBundleUrl"/>).</summary>
    public bool UiEnabled { get; set; } = true;

    /// <summary>Document title.</summary>
    public string Title { get; set; } = "Edge RPC";

    /// <summary>Document version.</summary>
    public string Version { get; set; } = "1.0.0";

    /// <summary>Document description.</summary>
    public string? Description { get; set; }

    /// <summary>clientId example shown in the envelope schema (e.g. "demo-app").</summary>
    public string? ClientIdExample { get; set; }

    /// <summary>Swagger UI stylesheet URL.</summary>
    public string SwaggerUiCssUrl { get; set; } = "https://unpkg.com/swagger-ui-dist@5/swagger-ui.css";

    /// <summary>Swagger UI bundle URL.</summary>
    public string SwaggerUiBundleUrl { get; set; } = "https://unpkg.com/swagger-ui-dist@5/swagger-ui-bundle.js";

    /// <summary>
    /// When true (default), <see cref="EdgeOpenApiExtensions.MapEdgeOpenApi"/> maps nothing
    /// outside the Development environment — the method catalog and parameter schemas are
    /// an attack map, so production exposure must be an explicit opt-in (set false and gate
    /// by network or auth policy yourself).
    /// </summary>
    public bool DevelopmentOnly { get; set; } = true;
}
